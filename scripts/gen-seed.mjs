// Generates migrations/0002_seed.sql from src/data/catalog.js.
// Run once when the catalogue file changes: `npm run seed:gen`.
import { writeFileSync } from "node:fs";
import {
  CATEGORIES, PRODUCTS, HAMPERS, BULK_PRODUCTS, BISCUIT_VARIETIES, PACKAGING_OPTIONS, TESTIMONIAL_DRAFTS,
} from "../src/data/catalog.js";
import { DEFAULT_SEO } from "../src/lib/seo-defaults.js";

const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : "'" + String(v).replace(/'/g, "''") + "'");
const paise = (rupees) => (rupees === null || rupees === undefined ? null : Math.round(rupees * 100));
const lines = ["-- Generated by scripts/gen-seed.mjs from src/data/catalog.js. Do not edit by hand.", ""];

for (const c of CATEGORIES) {
  lines.push(`INSERT INTO categories (slug, name, blurb, description, image, sort) VALUES (${[c.slug, c.name, c.blurb, c.description, c.image + ".webp", c.sort].map(q).join(", ")});`);
}
lines.push("");
let sort = 0;
for (const p of [...PRODUCTS, ...HAMPERS]) {
  sort += 10;
  const variants = (p.variants || []).map((v) => ({ id: v.id, label: v.label, price_paise: paise(v.price) }));
  const row = {
    slug: p.slug, name: p.name, category: p.category, short: p.short, description: p.description,
    packaging: p.packaging || "", weight: p.weight || "", price_paise: paise(p.price), image: p.image + ".webp",
    tags: JSON.stringify(p.tags || []), variants: JSON.stringify(variants), includes: JSON.stringify(p.includes || []),
    occasion: p.occasion || "", customisable: p.customisable || 0, bulk_note: p.bulk_note || "",
    featured: p.featured || 0, sort,
  };
  lines.push(`INSERT INTO products (${Object.keys(row).join(", ")}) VALUES (${Object.values(row).map(q).join(", ")});`);
}
lines.push("");

const settings = {
  store: {
    name: "Ovenroma Bakers",
    tagline: "Freshly Baked Happiness, Made for Every Occasion.",
    whatsapp: "", // set in Admin → Settings (digits with country code, e.g. 9198xxxxxxxx)
    phone: "", email: "", address: "", city: "", region: "", postcode: "", hours: "",
  },
  shipping: { flat_paise: 0, free_above_paise: null, note: "Delivery charges, if any, are shown at checkout." },
  bulk: {
    products: BULK_PRODUCTS.map((b) => ({ ...b, image: b.image + ".webp", price_paise: paise(b.price), price: undefined })),
    varieties: BISCUIT_VARIETIES,
    note: "Bulk orders should preferably be placed in advance. Delivery charges and final arrangements will be confirmed by our team.",
  },
  hampers: { packaging: PACKAGING_OPTIONS },
  home: {
    hero_title: "Freshly Baked. Beautifully Crafted. Made with Love.",
    hero_subtitle: "Discover delicious vegetarian bakery treats, artisanal biscuits, fresh kulchas and thoughtfully curated gift hampers.",
  },
  seo: DEFAULT_SEO,
};
for (const [k, v] of Object.entries(settings)) {
  lines.push(`INSERT INTO settings (key, value) VALUES (${q(k)}, ${q(JSON.stringify(v))});`);
}
lines.push("");
lines.push(`INSERT INTO banners (placement, title, subtitle, image, cta_label, cta_url, sort) VALUES ('promo', 'Making Every Celebration More Special.', 'Fresh kulchas, veg patties, biscuits and cupcakes at affordable bulk prices for Langar, Bhandara and community events.', '/assets/images/products/kulcha-bread.webp', 'Order for Langar & Bhandara', '/langar-bhandara-bulk-orders', 1);`);
for (const t of TESTIMONIAL_DRAFTS) {
  lines.push(`INSERT INTO testimonials (name, location, text, rating, active) VALUES (${[t.name, t.location, t.text, t.rating, 0].map(q).join(", ")});`);
}
writeFileSync(new URL("../migrations/0002_seed.sql", import.meta.url), lines.join("\n") + "\n");
console.log("wrote migrations/0002_seed.sql");
